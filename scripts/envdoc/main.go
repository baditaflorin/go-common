// Command envdoc generates docs/ENV.md, the list of environment variables that
// go-common packages declare in the env registry.
//
//	go run ./scripts/envdoc           write docs/ENV.md
//	go run ./scripts/envdoc -check    exit 1 if docs/ENV.md is stale, or if a package
//	                                  declares variables but is not imported below
//
// A package's variables only exist in the registry once the package is linked in,
// so this program imports every package that declares any. -check scans the module
// for env.Declare and env.Removed calls and fails if one lives in a package this
// file does not import, so the document cannot silently go incomplete.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	_ "github.com/baditaflorin/go-common/egress"
	"github.com/baditaflorin/go-common/env"
	_ "github.com/baditaflorin/go-common/graph"
	_ "github.com/baditaflorin/go-common/runtimetune"
	_ "github.com/baditaflorin/go-common/server"
)

const outFile = "docs/ENV.md"

func main() {
	check := flag.Bool("check", false, "fail if "+outFile+" is stale instead of writing it")
	flag.Parse()

	missing, err := undeclaredImports(".")
	if err != nil {
		fatal(err)
	}
	want := render()
	stale := false
	if *check {
		got, _ := os.ReadFile(outFile)
		stale = !bytes.Equal(got, want)
	} else if err := os.WriteFile(outFile, want, 0o644); err != nil {
		fatal(err)
	}
	for _, m := range missing {
		fmt.Fprintf(os.Stderr, "envdoc: package %s declares environment variables but scripts/envdoc/main.go does not import it; add a blank import\n", m)
	}
	if stale {
		fmt.Fprintf(os.Stderr, "envdoc: %s is stale; run `go run ./scripts/envdoc` and commit the result\n", outFile)
	}
	if stale || len(missing) > 0 {
		os.Exit(1)
	}
	if !*check {
		fmt.Printf("envdoc: wrote %s (%d variables)\n", outFile, len(env.Default.Snapshot(nil)))
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "envdoc:", err)
	os.Exit(1)
}

// undeclaredImports returns the packages (relative paths) that call env.Declare or
// env.Removed but are not imported by this program.
func undeclaredImports(root string) ([]string, error) {
	imported, err := ownImports(filepath.Join(root, "scripts", "envdoc", "main.go"))
	if err != nil {
		return nil, err
	}
	declaring := map[string]bool{}
	err = filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "testdata", "vendor", "lint", "env":
				return filepath.SkipDir // env itself defines Declare and mentions it in docs
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(b, []byte("env.Declare(")) || bytes.Contains(b, []byte("env.Removed(")) {
			dir := filepath.ToSlash(filepath.Dir(path))
			declaring[strings.TrimPrefix(dir, "./")] = true
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	var out []string
	for dir := range declaring {
		if dir == "scripts/envdoc" {
			continue
		}
		if !imported["github.com/baditaflorin/go-common/"+dir] {
			out = append(out, dir)
		}
	}
	sort.Strings(out)
	return out, nil
}

func ownImports(file string) (map[string]bool, error) {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.ImportsOnly)
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return nil, err
		}
		out[p] = true
	}
	return out, nil
}

func render() []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Code generated by `go run ./scripts/envdoc`; DO NOT EDIT. -->\n\n")
	b.WriteString("# Environment variables\n\n")
	b.WriteString("The variables that go-common packages declare in the `env` registry, with what they default to and what they do. ")
	b.WriteString("Each package still parses its own values; the registry lists them, checks the ones that are set when a service starts ")
	b.WriteString("(a value that does not parse, a variable that was removed, a likely typo of a declared name) and shows them, redacted, on the debug server's `/debug/config`. ")
	b.WriteString("To document a variable, declare it with `env.Declare` in its package; CI fails if this file is stale.\n\n")

	byOwner := map[string][]env.Info{}
	var owners []string
	for _, i := range env.Default.Snapshot(nil) {
		if _, ok := byOwner[i.Owner]; !ok {
			owners = append(owners, i.Owner)
		}
		byOwner[i.Owner] = append(byOwner[i.Owner], i)
	}
	sort.Strings(owners)
	for _, owner := range owners {
		fmt.Fprintf(&b, "## `%s`\n\n| Variable | Kind | Default | Description |\n| --- | --- | --- | --- |\n", owner)
		for _, i := range byOwner[owner] {
			def := i.Default
			switch {
			case i.Secret:
				def = "(secret)"
			case def == "":
				def = "unset"
			default:
				def = "`" + def + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", i.Name, i.Kind, def, strings.ReplaceAll(i.Doc, "|", `\|`))
		}
		b.WriteString("\n")
	}
	if removed := env.Default.RemovedList(); len(removed) > 0 {
		b.WriteString("## Removed\n\nStill setting one of these does nothing; a service that does is told at start-up.\n\n| Variable | Removed in | What to do |\n| --- | --- | --- |\n")
		for _, r := range removed {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.Name, r.Since, r.Advice)
		}
		b.WriteString("\n")
	}
	return b.Bytes()
}
